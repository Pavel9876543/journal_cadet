(() => {
    'use strict';

    const WRAPPER_CLASS = 'journal-responsive-table';
    const READY_ATTRIBUTE = 'data-responsive-table-ready';
    const EXISTING_CONTAINERS = [
        '.journal-responsive-table',
        '.table-scroll',
        '.table-responsive',
        '.results',
        '.tabular',
    ].join(',');

    function tableLabel(table) {
        const caption = table.querySelector('caption');
        if (caption && caption.textContent.trim()) {
            return caption.textContent.trim();
        }

        const section = table.closest('details, .module, .panel, section, article');
        const heading = section && section.querySelector(
            'summary, h1, h2, h3, h4, .module-title, .panel-title'
        );
        return heading && heading.textContent.trim()
            ? heading.textContent.trim()
            : 'Прокручиваемая таблица';
    }

    function makeScrollable(container, table) {
        if (!(container instanceof HTMLElement) || !container.isConnected) {
            return false;
        }
        container.classList.add(WRAPPER_CLASS);
        if (!container.hasAttribute('tabindex')) {
            container.tabIndex = 0;
        }
        if (!container.hasAttribute('role')) {
            container.setAttribute('role', 'region');
        }
        if (!container.hasAttribute('aria-label')) {
            container.setAttribute('aria-label', tableLabel(table));
        }
        container.dataset.responsiveTable = 'ready';
        table.setAttribute(READY_ATTRIBUTE, '1');
        return true;
    }

    function enhanceTable(table) {
        if (!(table instanceof HTMLTableElement)) {
            return;
        }
        if (
            table.dataset.noResponsiveTable !== undefined
            || table.hasAttribute(READY_ATTRIBUTE)
            || !table.isConnected
        ) {
            return;
        }

        const existing = table.closest(EXISTING_CONTAINERS);
        if (existing) {
            makeScrollable(existing, table);
            return;
        }

        // MutationObserver callbacks may still contain nodes that have already
        // been removed or moved by Select2/Django formsets. Never dereference a
        // stale parent: this was the source of the insertBefore null exception.
        const parent = table.parentElement;
        if (!parent || !parent.isConnected) {
            return;
        }

        const wrapper = document.createElement('div');
        wrapper.dataset.journalGeneratedTableWrapper = '1';
        parent.insertBefore(wrapper, table);
        wrapper.appendChild(table);
        makeScrollable(wrapper, table);
    }

    function enhanceTables(root = document) {
        if (root instanceof HTMLTableElement) {
            enhanceTable(root);
            return;
        }
        if (!(root instanceof Document || root instanceof DocumentFragment || root instanceof Element)) {
            return;
        }
        if (root instanceof Element && !root.isConnected) {
            return;
        }
        Array.from(root.querySelectorAll('table')).forEach(enhanceTable);
    }

    const pendingRoots = new Set();
    let enhancementFrame = null;

    function scheduleEnhancement(root) {
        if (!(root instanceof Element || root instanceof DocumentFragment || root instanceof Document)) {
            return;
        }
        pendingRoots.add(root);
        if (enhancementFrame !== null) {
            return;
        }
        enhancementFrame = window.requestAnimationFrame(() => {
            enhancementFrame = null;
            const roots = Array.from(pendingRoots);
            pendingRoots.clear();
            roots.forEach((candidate) => {
                if (candidate instanceof Element && !candidate.isConnected) {
                    return;
                }
                enhanceTables(candidate);
            });
        });
    }

    document.addEventListener('DOMContentLoaded', () => scheduleEnhancement(document));
    document.addEventListener('formset:added', (event) => {
        scheduleEnhancement(event.target || document);
    });

    const observer = new MutationObserver((records) => {
        records.forEach((record) => {
            record.addedNodes.forEach((node) => {
                if (!(node instanceof Element)) {
                    return;
                }
                // Ignore the wrapper generated by this script. Its table was
                // already processed synchronously in enhanceTable().
                if (node.dataset.journalGeneratedTableWrapper === '1') {
                    return;
                }
                scheduleEnhancement(node);
            });
        });
    });

    if (document.documentElement) {
        observer.observe(document.documentElement, {childList: true, subtree: true});
    }
})();
